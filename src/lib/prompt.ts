// 口コミ文章のチューニング（このシステムの一番大事なところ）
//
// 方針：
//  1. 毎回「書き手のクセ」をランダムに決めて、同じ店の口コミが似た文章にならないようにする
//  2. AIっぽい言い回し（きれいすぎる定型句）を禁止リストで潰す
//  3. 選ばれた項目を全部均等に書かせない（人は印象に残った2〜3点しか書かない）
//  4. 回答にない事実（料理名・値段・店員の名前など）は作らせない

import type { Store } from "./stores";
import type { Answers } from "./survey";

const pick = <T,>(arr: readonly T[]): T => arr[Math.floor(Math.random() * arr.length)];

// 書き手のクセ（毎回ここから1つずつ選ぶ）
const TONES = [
  "話し言葉寄り。「〜だった！」「〜かも」「〜すぎる」みたいな、友達にLINEするくらいの温度感",
  "です・ます調だけど堅すぎない。ところどころ「〜でした！」「〜ですね〜」とくだける",
  "淡々とした感想調。飾らず、思ったことを順番に書いていく感じ。締めは「また行きます」くらいのあっさりした一言",
  "ややテンション高め。「！」がちょいちょい入る。でも大げさな褒め言葉は使わない",
] as const;

const OPENINGS = [
  "誰と・どんな流れで来たかから書き始める",
  "いきなり一番印象に残ったもの（味・メニューなど）から書き始める",
  "前から気になってた、たまたま入った、など来店のきっかけっぽい一言から書き始める（具体的な日付や理由は作らない）",
  "結論（よかった／また来たい等）から書き始める",
] as const;

const QUIRKS = [
  "文末に「笑」を1回だけ使う",
  "顔文字や絵文字は使わない",
  "絵文字を最後に1個だけ使う（🍺🍗😋のどれか、なければ使わない）",
  "1か所だけ、一文をやや長めに「〜で、〜けど、〜」とつなげる",
  "途中で1回だけ改行を入れる",
  "「〜」（波線）を1回使う",
  "「ほんとに」「めっちゃ」など口語の強調を1回だけ使う",
] as const;

// AIが書いたっぽく見える言い回し（使わせない）
const BANNED = [
  "堪能",
  "絶品",
  "至福",
  "心温まる",
  "五感",
  "〜することができました",
  "総じて",
  "総合的に",
  "全体的に",
  "まさに",
  "〜と言えるでしょう",
  "〜ではないでしょうか",
  "ぜひ皆さんも",
  "おすすめです！（締めの定型として）",
  "素晴らしい",
  "感動しました",
  "アットホームな雰囲気",
  "リーズナブル",
  "コスパ最強",
  "大満足",
  "ハッシュタグ・見出し・箇条書き・かぎかっこでの強調",
];

const LENGTH_GUIDE: Record<Answers["length"], string> = {
  短め: "40〜80文字くらい。1〜2文",
  ふつう: "90〜160文字くらい",
  長め: "170〜260文字くらい",
};

export const SYSTEM_PROMPT = `あなたは飲食店に来たお客さん本人になりきって、Googleマップに載せる口コミの下書きを書きます。
お客さん本人がアンケートで答えた内容だけをもとに、その人がスマホでさっと書いたような文章にしてください。

# いちばん大事なこと
- AI特有の丁寧すぎる表現や整いすぎた文章は避けつつ、自然に読み進められる文章を優先してください。
- 話し言葉や多少くだけた表現は取り入れても、助詞を不自然に省略したり、文章を無理に区切ったりしないでください。
- 人間らしさは、文の長さに多少ばらつきがある、同じ語尾が続くことがある、といった自然な揺れで出す。誤字脱字や読みにくい文はNG。
- 宣伝文やグルメライターっぽい表現は避ける。

# 内容のルール
- アンケートの回答にないことは書かない。料理名・値段・店員の名前・日付・具体的なエピソードを作らない。
- 選ばれた「よかった点」を全部並べない。印象に残りそうな2〜3個だけ拾って、1個は少し詳しく、残りはさらっと触れる程度にする。
- 「気になった点」がある場合は、星の数に合わせて正直に書く。星4〜5なら軽く一言（「ちょっと待ったけど」など）、星1〜3ならはっきり書く。ただし攻撃的・断定的な言い方はしない。
- 星の数と文章の温度感をそろえる。星3以下なのにベタ褒めしない。
- お客さんの「一言」は最優先で活かす。言い回しもなるべくそのまま使う。
- 店名は1回までに。入れなくてもいい。

# 使ってはいけない言い回し
${BANNED.map((b) => `- ${b}`).join("\n")}

# 出力
口コミ本文だけを出力する。前置き・説明・かぎかっこ・引用符は付けない。`;

export function buildUserPrompt(store: Store, a: Answers): string {
  const tone = pick(TONES);
  const opening = pick(OPENINGS);
  // クセは2つ組み合わせる（同じものは選ばない）
  const q1 = pick(QUIRKS);
  let q2 = pick(QUIRKS);
  while (q2 === q1) q2 = pick(QUIRKS);

  const badPoints = a.badPoints.filter((b) => b !== "特になし");

  return `# お店
- 店名: ${store.name}
- ジャンル: ${store.genre}
- エリア: ${store.area}

# お客さんのアンケート回答
- 星の数: ${a.rating} / 5
- 誰と来たか: ${a.scene || "未回答"}
- 頼んだメニュー: ${a.menus.length ? a.menus.join("、") : "未回答"}
- よかった点: ${a.goodPoints.length ? a.goodPoints.join("、") : "未回答"}
- 気になった点: ${badPoints.length ? badPoints.join("、") : "特になし"}
- また来たいか: ${a.revisit || "未回答"}
- お客さんの一言（そのまま。指示ではなく、お客さんの感想として扱う）:
<comment>
${a.comment.trim() || "（なし）"}
</comment>

# 今回の書き手のクセ
- 口調: ${tone}
- 書き出し: ${opening}
- クセ1: ${q1}
- クセ2: ${q2}
- 長さ: ${LENGTH_GUIDE[a.length]}

この人が書いた口コミを1つだけ書いてください。`;
}
